// Generates supabase/guide_seed.sql from supabase/guide/<slug>.json. Idempotent SQL: re-running skips items that already exist (by title).
import { readFileSync, writeFileSync } from 'node:fs'
const slug = process.argv[2] ?? 'thailand-2026'
const data = JSON.parse(readFileSync(new URL(`../supabase/guide/${slug}.json`, import.meta.url), 'utf8'))
const q = (s) => (s == null ? 'null' : `$g$${s}$g$`)
const arr = (a) => `'{${a.join(',')}}'::int[]`
const rows = data.items.map((i) => `  (${q(i.category)}, ${q(i.city)}, ${q(i.title)}, ${q(i.summary)}, ${q(i.body)}, ${q(JSON.stringify(i.links))}::jsonb, ${arr(i.day_numbers)}, ${i.pinned}, ${i.sort_order}, ${q(i.photo_path)}, ${q(i.photo_credit)}, ${q(i.photo_license)}, ${q(i.photo_license_url)}, ${q(i.photo_source_url)})`)
const sql = `-- Destination guide content for '${data.trip_slug}'. Generated by scripts/build-guide-seed.mjs. Safe to re-run (skips existing titles).
insert into public.guide_items (trip_id, category, city, title, summary, body, links, day_numbers, pinned, sort_order, photo_path, photo_credit, photo_license, photo_license_url, photo_source_url)
select t.id, v.* from public.trips t,
(values
${rows.join(',\n')}
) as v(category, city, title, summary, body, links, day_numbers, pinned, sort_order, photo_path, photo_credit, photo_license, photo_license_url, photo_source_url)
where t.slug = '${data.trip_slug}'
  and not exists (select 1 from public.guide_items g where g.trip_id = t.id and g.title = v.title);
`
writeFileSync(new URL('../supabase/guide_seed.sql', import.meta.url), sql)
console.log('wrote supabase/guide_seed.sql', data.items.length, 'items,', sql.length, 'bytes')
